const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SHARED_BAIT = path.join(ROOT, "shared", "sanctuary", "bait");
const DEST_DIR = path.join(__dirname, "..", "src", "sanctuary");

const SYNC_HEADER = "// AUTO-GENERATED by sync-bait-module.js — do not edit by hand.\n";

function rewriteBaitImports(content) {
  return content.replace(/from "\.\.\/types"/g, 'from "./progression/_sanctuaryTypes"');
}

const srcPath = path.join(SHARED_BAIT, "catalog.ts");
const destPath = path.join(DEST_DIR, "baitCatalog.ts");

if (!fs.existsSync(srcPath)) {
  throw new Error(`Missing shared bait catalog: ${srcPath}`);
}

fs.mkdirSync(DEST_DIR, { recursive: true });

let content = SYNC_HEADER + fs.readFileSync(srcPath, "utf8");
content = rewriteBaitImports(content);
fs.writeFileSync(destPath, content);

console.log(`Synced bait catalog to ${destPath}`);

module.exports = { SYNC_HEADER, rewriteBaitImports };
