const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SRC_DIR = path.join(ROOT, "shared", "childProfile");
const DEST_DIR = path.join(__dirname, "..", "src", "childProfile");

const SYNC_HEADER = "// AUTO-GENERATED by sync-child-profile-module.js — do not edit by hand.\n";

const FILES = [
  "tierAccess.ts",
  "archetypeQuickCheck.ts",
  "archetypeCaptionBank.ts",
  "archetypeDeepCheck.ts",
  "childrenSummary.ts",
];

fs.mkdirSync(DEST_DIR, { recursive: true });

for (const file of FILES) {
  const src = path.join(SRC_DIR, file);
  const dest = path.join(DEST_DIR, file);
  if (!fs.existsSync(src)) {
    throw new Error(`Missing shared childProfile module file: ${src}`);
  }
  fs.writeFileSync(dest, SYNC_HEADER + fs.readFileSync(src, "utf8"));
}

console.log(`Synced ${FILES.length} childProfile module files to ${DEST_DIR}`);
