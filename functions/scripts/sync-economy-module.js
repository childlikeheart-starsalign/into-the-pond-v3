const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SHARED_ECONOMY = path.join(ROOT, "shared", "sanctuary", "economy");
const DEST_DIR = path.join(__dirname, "..", "src", "sanctuary", "economy");

const SYNC_HEADER = "// AUTO-GENERATED by sync-economy-module.js — do not edit by hand.\n";

const SKIP_FILES = new Set([
  "economy.test.ts",
  "callableResponses.test.ts",
  "buildEvent.ts",
  "errors.ts",
]);
const HAND_WRITTEN = new Set(["commitEconomyAction.ts", "resolveCallableIdempotency.ts"]);

function rewriteEconomyImports(content) {
  return content.replace(/from "\.\.\/wonder\/ledger"/g, 'from "../wonderLedger"');
}

function syncEconomyFile(fileName) {
  if (HAND_WRITTEN.has(fileName)) {
    return null;
  }

  const src = path.join(SHARED_ECONOMY, fileName);
  const dest = path.join(DEST_DIR, fileName);
  if (!fs.existsSync(src)) {
    throw new Error(`Missing shared economy file: ${src}`);
  }

  let content = SYNC_HEADER + fs.readFileSync(src, "utf8");
  content = rewriteEconomyImports(content);
  fs.writeFileSync(dest, content);
  return dest;
}

fs.mkdirSync(DEST_DIR, { recursive: true });

const economyFiles = fs
  .readdirSync(SHARED_ECONOMY)
  .filter((file) => file.endsWith(".ts") && !SKIP_FILES.has(file));

const synced = [];
for (const file of economyFiles) {
  const dest = syncEconomyFile(file);
  if (dest) synced.push(dest);
}

console.log(
  `Synced ${synced.length} economy files to ${DEST_DIR} (skipped hand-written: ${[...HAND_WRITTEN].join(", ")})`,
);
