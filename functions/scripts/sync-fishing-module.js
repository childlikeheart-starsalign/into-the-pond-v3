const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SHARED_FISHING = path.join(ROOT, "shared", "sanctuary", "fishing");
const SHARED_ROOT = path.join(ROOT, "shared", "sanctuary");
const DEST_DIR = path.join(__dirname, "..", "src", "sanctuary");
const PROGRESSION_DEST = path.join(DEST_DIR, "progression");

const SYNC_HEADER = "// AUTO-GENERATED by sync-fishing-module.js — do not edit by hand.\n";

const FISHING_FILES = [
  "encounterEngine.ts",
  "fishingClaimPresentation.ts",
  "fishingOutcomeMessages.ts",
  "castMapping.ts",
  "buildFishingClaimContext.ts",
  "castTiming.ts",
];

function rewriteFishingImports(content) {
  return content
    .replace(/from "\.\.\/types"/g, 'from "./types"')
    .replace(/from "\.\.\/economy\/callableResponses"/g, 'from "./economy/callableResponses"')
    .replace(/from "\.\.\/random"/g, 'from "./random"')
    .replace(/from "\.\.\/rods\/catalog"/g, 'from "./rodCatalog"')
    .replace(
      /from "\.\.\/progression\/rodFishingAccess"/g,
      'from "./progression/rodFishingAccess"',
    );
}

function syncFile(srcName, destName, rewriter = rewriteFishingImports) {
  const src = path.join(SHARED_FISHING, srcName);
  const dest = path.join(DEST_DIR, destName);
  if (!fs.existsSync(src)) {
    throw new Error(`Missing shared fishing file: ${src}`);
  }
  let content = SYNC_HEADER + fs.readFileSync(src, "utf8");
  content = rewriter(content);
  fs.writeFileSync(dest, content);
  return dest;
}

fs.mkdirSync(DEST_DIR, { recursive: true });

for (const file of FISHING_FILES) {
  syncFile(file, file);
}

const randomSrc = path.join(SHARED_ROOT, "random.ts");
const randomDest = path.join(DEST_DIR, "random.ts");
if (!fs.existsSync(randomSrc)) {
  throw new Error(`Missing shared random file: ${randomSrc}`);
}
fs.writeFileSync(randomDest, SYNC_HEADER + fs.readFileSync(randomSrc, "utf8"));

const rodAccessSrc = path.join(SHARED_ROOT, "progression", "rodFishingAccess.ts");
const rodAccessDest = path.join(PROGRESSION_DEST, "rodFishingAccess.ts");
if (!fs.existsSync(rodAccessSrc)) {
  throw new Error(`Missing shared rodFishingAccess file: ${rodAccessSrc}`);
}
let rodAccessContent = SYNC_HEADER + fs.readFileSync(rodAccessSrc, "utf8");
rodAccessContent = rodAccessContent
  .replace(/from "\.\.\/fishing\/encounterEngine"/g, 'from "../encounterEngine"')
  .replace(/from "\.\.\/types"/g, 'from "./_sanctuaryTypes"');
fs.mkdirSync(PROGRESSION_DEST, { recursive: true });
fs.writeFileSync(rodAccessDest, rodAccessContent);

const fishingPermissionServiceDest = path.join(PROGRESSION_DEST, "fishingPermissionService.ts");
fs.writeFileSync(
  fishingPermissionServiceDest,
  `${SYNC_HEADER}export { filterCreaturesByRodPermission } from "./rodFishingAccess";
import type { FishingRodId } from "./_sanctuaryTypes";

export function assertRodOwnedForCast(
  rodId: FishingRodId,
  state: string | undefined,
): void {
  if (state !== "ready" && state !== "equipped") {
    throw new Error(\`Rod \${rodId} is not owned for fishing\`);
  }
}
`,
);

console.log(
  `Synced ${FISHING_FILES.length} fishing files + random + rodFishingAccess to ${DEST_DIR}`,
);
