const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SRC_DIR = path.join(ROOT, "shared", "sanctuary", "progression");
const DEST_DIR = path.join(__dirname, "..", "src", "sanctuary", "progression");

const SYNC_HEADER = "// AUTO-GENERATED by sync-progression-module.js — do not edit by hand.\n";

const FILES = [
  "types.ts",
  "moduleRodMap.ts",
  "craftCosts.ts",
  "partsAwards.ts",
  "craftStates.ts",
  "subscriptionCraftGate.ts",
  "fishingPermissions.ts",
  "evaluateCraftable.ts",
];

const TYPES_SRC = path.join(ROOT, "shared", "sanctuary", "types.ts");
const TYPES_DEST = path.join(DEST_DIR, "_sanctuaryTypes.ts");

fs.mkdirSync(DEST_DIR, { recursive: true });

for (const file of FILES) {
  const src = path.join(SRC_DIR, file);
  const dest = path.join(DEST_DIR, file);
  if (!fs.existsSync(src)) {
    throw new Error(`Missing shared progression file: ${src}`);
  }
  let content = SYNC_HEADER + fs.readFileSync(src, "utf8");
  content = content.replace(/from "\.\.\/types"/g, 'from "./_sanctuaryTypes"');
  fs.writeFileSync(dest, content);
}

if (!fs.existsSync(TYPES_SRC)) {
  throw new Error(`Missing shared types file: ${TYPES_SRC}`);
}
fs.writeFileSync(TYPES_DEST, SYNC_HEADER + fs.readFileSync(TYPES_SRC, "utf8"));

console.log(`Synced ${FILES.length} progression files + types to ${DEST_DIR}`);
