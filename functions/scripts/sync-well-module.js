const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SRC_DIR = path.join(ROOT, "shared", "sanctuary", "well");
const DEST_DIR = path.join(__dirname, "..", "src", "sanctuary", "well");

const SYNC_HEADER = "// AUTO-GENERATED by sync-well-module.js — do not edit by hand.\n";

const FILES = [
  "types.ts",
  "computeAgeBand.ts",
  "catalog-4-6.ts",
  "catalog-6-12.ts",
  "catalog.ts",
  "wellQuestionService.ts",
];

fs.mkdirSync(DEST_DIR, { recursive: true });

for (const file of FILES) {
  const src = path.join(SRC_DIR, file);
  const dest = path.join(DEST_DIR, file);
  if (!fs.existsSync(src)) {
    throw new Error(`Missing shared well module file: ${src}`);
  }
  fs.writeFileSync(dest, SYNC_HEADER + fs.readFileSync(src, "utf8"));
}

console.log(`Synced ${FILES.length} well module files to ${DEST_DIR}`);
