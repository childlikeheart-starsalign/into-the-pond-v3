const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SHARED_WONDER = path.join(ROOT, "shared", "sanctuary", "wonder");
const DEST_DIR = path.join(__dirname, "..", "src", "sanctuary");

const SYNC_HEADER = "// AUTO-GENERATED by sync-wonder-module.js — do not edit by hand.\n";

const PAIRS = [
  { src: "rules.ts", dest: "wonderRules.ts" },
  { src: "ledger.ts", dest: "wonderLedger.ts" },
];

function rewriteWonderImports(content) {
  return content.replace(/from "\.\.\/types"/g, 'from "./types"');
}

fs.mkdirSync(DEST_DIR, { recursive: true });

for (const { src, dest } of PAIRS) {
  const srcPath = path.join(SHARED_WONDER, src);
  const destPath = path.join(DEST_DIR, dest);
  if (!fs.existsSync(srcPath)) {
    throw new Error(`Missing shared wonder file: ${srcPath}`);
  }
  let content = SYNC_HEADER + fs.readFileSync(srcPath, "utf8");
  content = rewriteWonderImports(content);
  fs.writeFileSync(destPath, content);
}

console.log(`Synced ${PAIRS.length} wonder files to ${DEST_DIR}`);

module.exports = { SYNC_HEADER, rewriteWonderImports, PAIRS };
